export const normalize = (s: string): string => {
  if (!s) return '';
  let res = s.toLowerCase();
  const replacements: Record<string, string> = {
    'é': 'e', 'è': 'e', 'ê': 'e', 'ë': 'e',
    'à': 'a', 'â': 'a', 'ä': 'a',
    'î': 'i', 'ï': 'i',
    'ô': 'o', 'ö': 'o',
    'û': 'u', 'ü': 'u', 'ù': 'u',
    'ç': 'c'
  };
  for (const [k, v] of Object.entries(replacements)) {
    res = res.replaceAll(k, v);
  }
  // Separate digits and letters, e.g. "150g" -> "150 g"
  res = res.replace(/(\d+)([a-zA-Z]+)/g, '$1 $2');
  res = res.replace(/([a-zA-Z]+)(\d+)/g, '$1 $2');

  // Remove non-alphanumeric except spaces
  res = res.replace(/[^a-z0-9\s]/g, ' ');
  // Collapse multiple spaces
  res = res.replace(/\s+/g, ' ').trim();
  return res;
};

const escapeRegExp = (str: string): string => {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
};

export const findGenericProduct = (rawName: string, itemRayon: string = ''): string => {
  const normName = normalize(rawName);

  if (itemRayon && (itemRayon.toUpperCase().includes('BAZAR') || itemRayon.toUpperCase().includes('BOUTIQUE'))) {
    return '';
  }

  for (const [generic, keywords] of Object.entries(orderedKeywordMappings)) {
    // Check coherence rules if rayon is set and generic has constraints
    if (coherenceRules[generic] && itemRayon && itemRayon !== 'N/A' && itemRayon !== 'AUTRE') {
      const allowed = coherenceRules[generic];
      const rayonLower = itemRayon.toLowerCase();
      if (!allowed.some(kw => rayonLower.includes(kw.toLowerCase()))) {
        continue; // Skip matching this generic product, it violates rayon coherence!
      }
    }

    for (const kw of keywords) {
      let pattern: RegExp;
      if (kw.endsWith('*')) {
        const normKw = normalize(kw.slice(0, -1));
        pattern = new RegExp('\\b' + escapeRegExp(normKw) + '\\w*', 'i');
      } else {
        const normKw = normalize(kw);
        pattern = new RegExp('\\b' + escapeRegExp(normKw) + '[sx]?\\b', 'i');
      }

      if (pattern.test(normName)) {
        return generic;
      }
    }
  }

  return '';
};

export const cleanRayon = (rawRayon: string): string => {
  if (!rawRayon) return 'AUTRE';
  let r = rawRayon.toUpperCase().trim();
  if (r.startsWith('>>')) {
    r = r.substring(2).trim();
  }

  const mapping: Record<string, string[]> = {
    'LIQUIDES': ['LIQUIDE', 'LIQUIDES', 'BOISSONS', 'LIQUIDES BIO'],
    'HYGIENE': ['HYGIENE', 'PARFUMERIE', 'DPH', 'ENTRETIEN'],
    'BOUCHERIE': ['BOUCHERIE', 'VOLAILLE', 'VOLAILLES'],
    'CHARCUTERIE': ['CHARCUTERIE'],
    'CREMERIE': ['CREMERIE', 'LAIT', 'CREME'],
    'BOULANGERIE': ['BOULANGERIE', 'VIENNOISERIE', 'PATISSERIE', 'PAIN'],
    'SURGELES': ['SURGELE', 'SURGELES'],
    'FRUITS & LEGUMES': ['FRUITS', 'LEGUMES'],
    'SAURISSERIE': ['SAURISSERIE'],
    'POISSONNERIE': ['POISSONNERIE'],
    'EPICERIE': ['EPICERIE'],
    'BAZAR': ['BAZAR', 'BOUTIQUE', 'TEXTILE', 'BRICOLAGE', 'AUTO', 'MAISON']
  };

  for (const [macro, keywords] of Object.entries(mapping)) {
    if (keywords.some(kw => r.includes(kw))) {
      return macro;
    }
  }

  return 'EPICERIE';
};

export const getCategoryFromRayon = (rayon: string): string => {
  if (!rayon) return 'Alimentaire';
  const rUpper = rayon.toUpperCase();
  if (rUpper.includes('HYGIENE') || rUpper.includes('PARFUMERIE') || rUpper.includes('ENTRETIEN')) {
    return 'Hygiène';
  }
  if (rUpper.includes('BAZAR') || rUpper.includes('BOUTIQUE')) {
    return 'Bazar / Électroménager';
  }
  return 'Alimentaire';
};
